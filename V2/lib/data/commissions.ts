/** Inline copy of a portfolio piece for a delivery (portfolio pieces were cut from these deliveries). */
function deliveredCopy(portfolioId: string, id: string, overrides: Partial<Video> = {}): Video {
  const source = videos.find((v) => v.id === portfolioId);
  if (!source) throw new Error(`Unknown portfolio video ${portfolioId}`);
  // Deliveries never carry performance stats; those are reported later on the portfolio piece.
  // eslint-disable-next-line @typescript-eslint/no-unused-vars
  const { stats, ...rest } = source;
  return { ...rest, ...overrides, id };
}

